import { test, expect } from '@playwright/test';
import { spawn } from 'node:child_process';
import { resolve } from 'node:path';

test('real mode connection test, sync, view, port, CLI and reboot use the Telnet transport', async ({page}) => {
    test.setTimeout(90000);
    const server=spawn(resolve('.tools/php/php.exe'),[resolve('tests/Fixtures/zte-telnet-server.php'),'device-labels'],{env:{...process.env,MIBS:process.platform==='win32'?';':':'},windowsHide:true});
    let output='';
    const port=await new Promise((resolvePort,reject)=>{
        server.stdout.on('data',chunk=>{ output+=chunk.toString(); const first=output.split('\n')[0]; if(first.endsWith('}'))resolvePort(JSON.parse(first).port); });
        server.once('error',reject); server.once('exit',code=>reject(new Error('Fixture stopped '+code)));
    });
    const errors=[]; page.on('pageerror',e=>errors.push(e.message));
    try {
        await page.goto('/login');
        await page.getByLabel('Email',{exact:true}).fill('owner@nusantara.test');
        await page.getByLabel('Kata sandi').fill('NmsDemo2026!');
        await page.getByRole('button',{name:'Masuk ke dashboard'}).click();
        const card=page.locator('.olt-card').first();
        await card.getByRole('button',{name:/Edit /}).click();
        await page.getByLabel('Mode koneksi',{exact:true}).selectOption('real');
        await page.getByLabel('IP Address Private/Public').fill('127.0.0.1');
        await page.getByLabel('Port Telnet',{exact:true}).fill(String(port));
        await page.getByLabel('Username Telnet',{exact:true}).fill('admin');
        await page.getByLabel('Password Telnet',{exact:true}).fill('test-secret');
        await page.getByRole('button',{name:'Test Connection',exact:true}).click();
        await expect(page.locator('dialog[x-ref="dialog"]')).toContainText('Koneksi nyata berhasil.');
        await page.getByRole('button',{name:'Simpan OLT',exact:true}).click();
        await expect(card).toContainText('REAL');
        await expect(card).toContainText('Belum pernah sinkronisasi');
        const shortcut=card.getByRole('button',{name:/Web CLI/});
        await expect(shortcut).toBeEnabled();
        await shortcut.click();
        await expect(page.getByLabel('Perintah CLI')).toBeFocused();
        await page.getByLabel('Perintah CLI').fill('show version-running');
        await page.getByRole('button',{name:'Jalankan perintah'}).click();
        await expect(page.locator('.terminal-output')).toContainText('V2.1.0');
        await page.keyboard.press('Escape');
        await card.getByRole('button',{name:'View',exact:true}).click();
        await page.getByRole('button',{name:'Buka Web CLI (>_)',exact:true}).click();
        await expect(page.getByLabel('Perintah CLI')).toBeFocused();
        await expect(page.locator('dialog[x-ref="dialog"]')).toContainText('Web CLI');
        await page.keyboard.press('Escape');
        await card.getByRole('button',{name:'Sync',exact:true}).click();
        await expect(page.getByRole('status')).toContainText('Sinkronisasi OLT nyata berhasil',{timeout:20000});
        await expect(card).toContainText('1 / 2');
        await card.getByRole('button',{name:'View',exact:true}).click();
        await expect(page.locator('dialog[x-ref="dialog"]')).toContainText('V2.1.0');
        await expect(page.locator('dialog[x-ref="dialog"]')).toContainText('38%');
        await expect(page.locator('dialog[x-ref="dialog"]')).toContainText('GTGO');
        await page.keyboard.press('Escape');
        await card.getByRole('button',{name:'Port',exact:true}).click();
        await expect(page.getByText('Mengambil data langsung dari OLT...',{exact:true})).toBeHidden();
        await expect(page.locator('dialog tbody tr')).toHaveCount(8);
        await page.keyboard.press('Escape');
        await card.getByRole('button',{name:'ONU',exact:true}).click();
        await expect(page.locator('dialog tbody tr')).toHaveCount(2);
        await expect(page.locator('dialog tbody tr').first().locator('td').first()).toHaveText('Budi Rumah');
        await expect(page.getByRole('columnheader',{name:/Serial/})).toBeVisible();
        await expect(page.locator('dialog tbody tr').first()).toContainText('-27.00 dBm');
        await expect(page.locator('dialog tbody tr').first()).toContainText('Buruk');
        await page.locator('dialog tbody tr').first().getByRole('button',{name:'Reboot ONU',exact:true}).click();
        await page.getByRole('button',{name:'Ya, reboot onu',exact:true}).click();
        await expect(page.locator('.confirmation-panel')).toHaveCount(0);
        await expect(page.locator('dialog tbody tr').first().getByRole('button',{name:'Reboot ONU',exact:true})).toBeEnabled();
        await expect(page.locator('dialog tbody tr').first()).toContainText('Online');
        await page.keyboard.press('Escape');
        await card.getByRole('button',{name:/Web CLI/}).click();
        await page.getByLabel('Perintah CLI').fill('show gpon onu uncfg');
        await page.getByRole('button',{name:'Jalankan perintah'}).click();
        await expect(page.locator('.terminal-output')).toContainText('No related information');
        await page.getByLabel('Perintah CLI').fill('show rejected');
        await page.getByRole('button',{name:'Jalankan perintah'}).click();
        await expect(page.locator('.terminal-output')).toContainText("Perintah 'show rejected' ditolak OLT: %Error: Invalid input [REDACTED]");
        await expect(page.locator('.terminal-output')).not.toContainText('test-secret');
        await expect(page.locator('.terminal-output')).not.toContainText('test-community');
        await page.keyboard.press('Escape');
        await card.getByRole('button',{name:/Edit /}).click();
        await expect(page.getByLabel('Username Telnet',{exact:true})).toHaveValue('admin');
        await page.setViewportSize({width:1440,height:1100});
        await page.screenshot({path:'docs/real-connection-form.png'});
        expect(errors).toEqual([]);
    } finally { server.kill(); }
});

